import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const tokensJsonPath = path.join(rootDir, 'docs', 'design', 'tokens.json');
const outDir = path.join(rootDir, 'src', 'styles');

if (!fs.existsSync(tokensJsonPath)) {
  console.error(`Error: Tokens JSON not found at ${tokensJsonPath}`);
  process.exit(1);
}

const tokens = JSON.parse(fs.readFileSync(tokensJsonPath, 'utf8'));

fs.mkdirSync(outDir, { recursive: true });

function kebabCase(str) {
  return str.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

// 1. Generate tokens.generated.css
let cssLines = [];
cssLines.push('/* Auto-generated by scripts/generate-tokens.mjs - DO NOT EDIT MANUALLY */');
cssLines.push(':root {');

// Colors
for (const [key, value] of Object.entries(tokens.color || {})) {
  cssLines.push(`  --color-${kebabCase(key)}: ${value};`);
}

// Additional color aliases
cssLines.push(`  --color-ink: ${tokens.color?.textPrimary || '#252D2F'};`);

// Radius
for (const [key, value] of Object.entries(tokens.radius || {})) {
  cssLines.push(`  --radius-${kebabCase(key)}: ${value};`);
}

// Space
for (const [key, value] of Object.entries(tokens.space || {})) {
  cssLines.push(`  --space-${kebabCase(key)}: ${value};`);
}

// Stroke
for (const [key, value] of Object.entries(tokens.stroke || {})) {
  cssLines.push(`  --stroke-${kebabCase(key)}: ${value};`);
}

// Shadows
for (const [key, value] of Object.entries(tokens.shadow || {})) {
  cssLines.push(`  --shadow-${kebabCase(key)}: ${value};`);
}

// Motion
for (const [key, value] of Object.entries(tokens.motion?.duration || {})) {
  cssLines.push(`  --motion-duration-${kebabCase(key)}: ${value};`);
}
for (const [key, value] of Object.entries(tokens.motion?.easing || {})) {
  cssLines.push(`  --motion-easing-${kebabCase(key)}: ${value};`);
}

// Timeline
for (const [key, value] of Object.entries(tokens.timeline || {})) {
  cssLines.push(`  --timeline-${kebabCase(key)}: ${value};`);
}

cssLines.push('}');
cssLines.push('');

// Tailwind v4 @theme extensions
cssLines.push('@theme {');
for (const [key] of Object.entries(tokens.color || {})) {
  cssLines.push(`  --color-${kebabCase(key)}: var(--color-${kebabCase(key)});`);
}
cssLines.push(`  --color-ink: var(--color-ink);`);

for (const [key] of Object.entries(tokens.radius || {})) {
  cssLines.push(`  --radius-${kebabCase(key)}: var(--radius-${kebabCase(key)});`);
}

  // Note: We deliberately do not map tokens.space to --spacing-{xs,sm,md,lg} in @theme
  // because in Tailwind v4 that overrides container max-w-* and w-* utilities
  // (e.g. max-w-md becomes 12px instead of 28rem). Tokens remain available as var(--space-*).


cssLines.push(`  --font-grotesk: var(--font-inter), system-ui, sans-serif;`);
cssLines.push(`  --font-arabic: var(--font-ibm-plex-arabic), system-ui, sans-serif;`);
cssLines.push('}');

fs.writeFileSync(path.join(outDir, 'tokens.generated.css'), cssLines.join('\n') + '\n');

// 2. Generate tokens.generated.ts
const tsContent = `// Auto-generated by scripts/generate-tokens.mjs - DO NOT EDIT MANUALLY
export const tokens = ${JSON.stringify(
  {
    color: tokens.color,
    radius: tokens.radius,
    space: tokens.space,
    stroke: tokens.stroke,
    font: tokens.font,
    shadow: tokens.shadow,
    motion: tokens.motion,
    timeline: tokens.timeline,
  },
  null,
  2
)} as const;

export type ColorToken = keyof typeof tokens.color;
export type RadiusToken = keyof typeof tokens.radius;
export type SpaceToken = keyof typeof tokens.space;
export type StrokeToken = keyof typeof tokens.stroke;
`;

fs.writeFileSync(path.join(outDir, 'tokens.generated.ts'), tsContent + '\n');
console.log('Successfully generated tokens in src/styles/');
