export function findLabCatalogItem(nameOrAbbr: string): LabCatalogItem | undefined {
  const q = nameOrAbbr.toLowerCase().trim();
  return EGYPTIAN_LAB_CATALOG.find((item) => {
    if (item.name.toLowerCase() === q) return true;
    if (item.abbreviation.toLowerCase() === q) return true;
    if (item.arabicName.toLowerCase() === q) return true;
    if (item.synonyms && item.synonyms.some((s) => s.toLowerCase() === q)) return true;
    if (item.name.toLowerCase().includes(q) || q.includes(item.name.toLowerCase())) return true;
    return false;
  });
}
